import socket
import threading
import json
import time

# ============================================================
# CONFIGURAÇÕES DO SISTEMA
# ============================================================

HOST = "127.0.0.1"
PORT = 0
TOTAL_PROCESSOS = 3

lock_log = threading.Lock()
servidor_pronto = threading.Event()

relogio_servidor = 0
registro_nomes = {}
resultados_rpc = {}
relogios_processos = {}


def log(mensagem):
    with lock_log:
        print(mensagem, flush=True)


def incrementar_relogio_servidor():
    global relogio_servidor
    relogio_servidor += 1
    return relogio_servidor


def atualizar_relogio_servidor(relogio_recebido):
    global relogio_servidor
    relogio_servidor = max(
        relogio_servidor,
        relogio_recebido
    ) + 1
    return relogio_servidor


def enviar_servidor(conexao, mensagem):
    mensagem["lamport"] = incrementar_relogio_servidor()
    dados = json.dumps(mensagem) + "\n"
    conexao.sendall(dados.encode("utf-8"))


def receber_servidor(arquivo):
    linha = arquivo.readline()

    if not linha:
        raise ConnectionError("Conexão encerrada.")

    mensagem = json.loads(linha)

    atualizar_relogio_servidor(
        mensagem.get("lamport", 0)
    )

    return mensagem


# ============================================================
# SERVIÇO DE NOMES
# ============================================================

def registrar_processo(processo, identificador, conexao):
    registro_nomes[processo] = {
        "id": identificador,
        "conexao": conexao
    }

    log(
        f"[SERVIÇO DE NOMES] {processo} "
        f"registrado com sucesso."
    )


# ============================================================
# SERVIDOR / MIDDLEWARE COORDENADOR
# ============================================================

def servidor():
    global PORT

    servidor_socket = socket.socket(
        socket.AF_INET,
        socket.SOCK_STREAM
    )

    servidor_socket.setsockopt(
        socket.SOL_SOCKET,
        socket.SO_REUSEADDR,
        1
    )

    servidor_socket.bind((HOST, PORT))
    PORT = servidor_socket.getsockname()[1]
    servidor_socket.listen(TOTAL_PROCESSOS)
    servidor_socket.settimeout(20)

    servidor_pronto.set()

    log("\n========== SERVIDOR INICIADO ==========")
    log(f"[SERVIDOR] Porta de comunicação: {PORT}")
    log(
        f"[SERVIDOR] Aguardando "
        f"{TOTAL_PROCESSOS} processos...\n"
    )

    conexoes = {}
    arquivos = {}

    try:
        # ----------------------------------------------------
        # REGISTRO DOS PROCESSOS
        # ----------------------------------------------------

        for _ in range(TOTAL_PROCESSOS):
            conexao, endereco = servidor_socket.accept()

            arquivo = conexao.makefile(
                "r",
                encoding="utf-8"
            )

            mensagem = receber_servidor(arquivo)

            processo = mensagem["processo"]
            identificador = mensagem["id"]

            registrar_processo(
                processo,
                identificador,
                conexao
            )

            conexoes[processo] = conexao
            arquivos[processo] = arquivo

            enviar_servidor(conexao, {
                "tipo": "REGISTRO_OK"
            })

        log(
            "\n[SERVIDOR] Todos os processos "
            "foram registrados."
        )

        # ----------------------------------------------------
        # ETAPA 1 - CHAMADA REMOTA DE PROCEDIMENTO (RPC)
        # ----------------------------------------------------

        log("\n========== ETAPA 1: RPC ==========")

        tarefas = {
            "PROCESSO 1": [2, 3],
            "PROCESSO 2": [4, 5],
            "PROCESSO 3": [6, 7]
        }

        eventos_rpc = []

        for processo, valores in tarefas.items():

            log(
                f"[RPC] Solicitando multiplicação "
                f"ao {processo}."
            )

            enviar_servidor(conexoes[processo], {
                "tipo": "RPC",
                "operacao": "MULTIPLICACAO",
                "valores": valores
            })

            resposta = receber_servidor(
                arquivos[processo]
            )

            resultado = resposta["resultado"]
            relogio_processo = resposta["lamport"]

            resultados_rpc[processo] = {
                "operacao": "MULTIPLICACAO",
                "valores": valores,
                "resultado": resultado,
                "lamport": relogio_processo
            }

            relogios_processos[processo] = relogio_processo

            eventos_rpc.append({
                "processo": processo,
                "lamport": relogio_processo
            })

            log(
                f"[RPC] {processo}: "
                f"{valores[0]} x {valores[1]} "
                f"= {resultado} "
                f"(Lamport: {relogio_processo})"
            )

        resultado_global = sum(
            item["resultado"]
            for item in resultados_rpc.values()
        )

        log(
            f"\n[RESULTADO] Resultado global: "
            f"{resultado_global}"
        )

        # ----------------------------------------------------
        # ETAPA 2 - ELEIÇÃO DE COORDENADOR (BULLY)
        # ----------------------------------------------------

        log("\n========== ETAPA 2: ELEIÇÃO BULLY ==========")

        log(
            "[BULLY] Verificando os processos ativos "
            "e seus identificadores."
        )

        processos_ativos = list(registro_nomes.items())

        coordenador = max(
            processos_ativos,
            key=lambda item: item[1]["id"]
        )[0]

        log(
            f"[BULLY] Maior identificador pertence "
            f"ao {coordenador}."
        )

        for processo in conexoes:

            enviar_servidor(conexoes[processo], {
                "tipo": "COORDINATOR",
                "coordenador": coordenador
            })

            resposta = receber_servidor(
                arquivos[processo]
            )

            relogios_processos[processo] = resposta["lamport"]

            log(
                f"[BULLY] {processo} confirmou "
                f"o novo coordenador."
            )

        log(
            f"\n[BULLY] Novo coordenador eleito: "
            f"{coordenador}."
        )

        # ----------------------------------------------------
        # ETAPA 3 - ORDENAÇÃO LÓGICA DOS EVENTOS
        # ----------------------------------------------------

        eventos_ordenados = sorted(
            eventos_rpc,
            key=lambda evento: (
                evento["lamport"],
                evento["processo"]
            )
        )

        ordem_logica = [
            f"{evento['processo']} "
            f"(Lamport {evento['lamport']})"
            for evento in eventos_ordenados
        ]

        log("\n========== ORDEM LÓGICA DOS EVENTOS ==========")

        for posicao, evento in enumerate(
            ordem_logica,
            start=1
        ):
            log(f"{posicao}. {evento}")

        # ----------------------------------------------------
        # ETAPA 4 - SINCRONIZAÇÃO DO ESTADO GLOBAL
        # ----------------------------------------------------

        log("\n========== ETAPA 4: SINCRONIZAÇÃO ==========")

        estado_global = {
            "coordenador": coordenador,
            "resultados_rpc": resultados_rpc,
            "relogios_lamport": relogios_processos,
            "ordem_logica": ordem_logica,
            "resultado_global": resultado_global
        }

        confirmacoes = 0

        for processo in conexoes:

            log(
                f"[SINCRONIZAÇÃO] Enviando estado "
                f"global para {processo}."
            )

            enviar_servidor(conexoes[processo], {
                "tipo": "SYNC",
                "estado": estado_global
            })

            resposta = receber_servidor(
                arquivos[processo]
            )

            if resposta["tipo"] == "ACK":
                confirmacoes += 1

                relogios_processos[processo] = (
                    resposta["lamport"]
                )

                log(
                    f"[ACK] Confirmação recebida "
                    f"de {processo}."
                )

        # ----------------------------------------------------
        # RESULTADO FINAL
        # ----------------------------------------------------

        log("\n========== RESULTADO FINAL ==========")

        log(
            f"[SERVIDOR] Resultado RPC global: "
            f"{resultado_global}"
        )

        log(
            f"[SERVIDOR] Coordenador eleito: "
            f"{coordenador}"
        )

        log(
            f"[SERVIDOR] Confirmações ACK: "
            f"{confirmacoes}/{TOTAL_PROCESSOS}"
        )

        log(
            f"[SERVIDOR] Relógios lógicos: "
            f"{relogios_processos}"
        )

        log(
            "[SERVIDOR] Estado global sincronizado."
        )

        log(
            "[SERVIDOR] Simulação concluída com sucesso."
        )

        # ----------------------------------------------------
        # ENCERRAMENTO
        # ----------------------------------------------------

        for processo in conexoes:

            enviar_servidor(conexoes[processo], {
                "tipo": "ENCERRAR"
            })

        log("\n[SERVIDOR] Encerrando conexões.")

    except Exception as erro:
        log(f"[ERRO NO SERVIDOR] {erro}")

    finally:
        for arquivo in arquivos.values():
            try:
                arquivo.close()
            except OSError:
                pass

        for conexao in conexoes.values():
            try:
                conexao.close()
            except OSError:
                pass

        servidor_socket.close()


# ============================================================
# PROCESSOS DISTRIBUÍDOS
# ============================================================

def processo_distribuido(numero):

    nome = f"PROCESSO {numero}"

    servidor_pronto.wait()

    cliente = socket.socket(
        socket.AF_INET,
        socket.SOCK_STREAM
    )

    cliente.settimeout(20)

    arquivo = None
    relogio_local = 0

    def enviar_processo(mensagem):
        nonlocal relogio_local

        relogio_local += 1

        mensagem["lamport"] = relogio_local

        cliente.sendall(
            (
                json.dumps(mensagem) + "\n"
            ).encode("utf-8")
        )

    def receber_processo():
        nonlocal relogio_local

        linha = arquivo.readline()

        if not linha:
            raise ConnectionError(
                "Conexão encerrada pelo servidor."
            )

        mensagem = json.loads(linha)

        relogio_local = max(
            relogio_local,
            mensagem.get("lamport", 0)
        ) + 1

        return mensagem

    try:
        cliente.connect((HOST, PORT))

        arquivo = cliente.makefile(
            "r",
            encoding="utf-8"
        )

        # ----------------------------------------------------
        # REGISTRO NO SERVIÇO DE NOMES
        # ----------------------------------------------------

        relogio_local += 1

        cliente.sendall(
            (
                json.dumps({
                    "tipo": "REGISTER",
                    "processo": nome,
                    "id": numero,
                    "lamport": relogio_local
                }) + "\n"
            ).encode("utf-8")
        )

        log(f"[{nome}] Conectado ao servidor.")

        resposta = receber_processo()

        if resposta["tipo"] == "REGISTRO_OK":
            log(
                f"[{nome}] Registro confirmado "
                f"no serviço de nomes."
            )

        # ----------------------------------------------------
        # RECEBIMENTO DAS OPERAÇÕES DO SERVIDOR
        # ----------------------------------------------------

        while True:

            mensagem = receber_processo()
            tipo = mensagem["tipo"]

            # RPC - MULTIPLICAÇÃO

            if tipo == "RPC":

                valores = mensagem["valores"]

                resultado = valores[0] * valores[1]

                log(
                    f"[{nome}] Executando RPC: "
                    f"{valores[0]} x {valores[1]} "
                    f"= {resultado}."
                )

                enviar_processo({
                    "tipo": "RPC_RESULT",
                    "resultado": resultado
                })

            # ELEIÇÃO DE COORDENADOR

            elif tipo == "COORDINATOR":

                coordenador = mensagem["coordenador"]

                log(
                    f"[{nome}] Reconheceu "
                    f"{coordenador} como coordenador."
                )

                enviar_processo({
                    "tipo": "COORDINATOR_ACK"
                })

            # SINCRONIZAÇÃO DO ESTADO GLOBAL

            elif tipo == "SYNC":

                estado = mensagem["estado"]

                maior_relogio = max(
                    estado["relogios_lamport"].values()
                )

                relogio_local = max(
                    relogio_local,
                    maior_relogio
                ) + 1

                log(
                    f"[{nome}] Recebeu o estado global. "
                    f"Resultado: {estado['resultado_global']}."
                )

                log(
                    f"[{nome}] Atualizou o relógio "
                    f"lógico para {relogio_local}."
                )

                enviar_processo({
                    "tipo": "ACK"
                })

            # ENCERRAMENTO

            elif tipo == "ENCERRAR":

                log(
                    f"[{nome}] Encerrando participação."
                )

                break

    except Exception as erro:

        log(f"[{nome}] Erro: {erro}")

    finally:

        if arquivo:
            arquivo.close()

        cliente.close()


# ============================================================
# EXECUÇÃO GERAL
# ============================================================

print(
    "INICIANDO SIMULAÇÃO DE SISTEMA DISTRIBUÍDO - AVA 2"
)

thread_servidor = threading.Thread(
    target=servidor
)

thread_servidor.start()

# Aguarda o servidor estar pronto

servidor_pronto.wait()

# Inicia os três processos distribuídos

threads_processos = []

for numero in range(1, TOTAL_PROCESSOS + 1):

    thread = threading.Thread(
        target=processo_distribuido,
        args=(numero,)
    )

    threads_processos.append(thread)
    thread.start()

# Aguarda o término dos processos

for thread in threads_processos:
    thread.join()

thread_servidor.join()

print("\nEXECUÇÃO FINALIZADA.")